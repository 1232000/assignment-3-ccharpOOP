// Q1: What is the difference between static binding and dynamic binding? When does each one happen?
// static binding happens at compile time, the compiler decides which method to call
// dynamic binding happens at runtime, the program decides which overridden method to call

// Q2: What is the difference between method overloading and method overriding?
// Method overloading => having multiple methods with the same name but different parameters
// Method overriding => a child class provides its own implementation of a method from the parent class

// Q3: What keywords are used for Method Overriding? What does each one mean?
// virtual: allows a method in the parent class to be overridden
// override: provides a new implementation of a virtual or abstract method in the child class
// abstract: defines a method without an implementation, child class must implement it unless it is also abstract
